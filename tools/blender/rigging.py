def _puppet(R):
    c, h = R.c, R.c.h
    top_z = c.ey - c.eye_rim_r - 0.08         # sockfeat_c.feat_puppet: the mouth's top edge,
    w0, depth = 0.56, 0.78                     # its half width and depth (the lips go 6% wider)

    def top(u):
        return top_z - 0.06 * (1 - (u / w0) ** 2)

    def bot(u):
        return top_z - depth * max(1 - (u / w0) ** 2.4, 0.0) ** 0.55

    # the hinge sits 2 units behind the mouth, so turning the Jaw about +X (up to ~8 deg) drops the
    # lower jaw nearly straight down (a slide down its -Y does the same); a closer hinge swings the
    # lip in or out of the face
    zm = top_z - depth / 2
    R.add("Jaw", "Leg4", (0.0, 2.0, zm), (0.0, 2.0, top_z + 0.3), "jaw", hint=dict(turn=8, slide=0.3))
    base = R.base

    def jaw(p):
        """The Jaw's share: 0 on the mouth's top edge, rising LINEARLY to 1 on its bottom edge (the
        mouth plates have vertices only on those two edges, so the skin under them must move the
        same linear way or it pokes through), 1 on the chin, fading out below it and to the sides."""
        x, y, z = p
        fr = _smooth((-y - 0.1) / 0.3)                          # the front only
        if fr <= 0.0:
            return 0.0
        u = min(abs(x), w0)
        zt, zb = top(u), bot(u)
        a = min(max((zt - z) / max(zt - zb, 0.1), 0.0), 1.0)
        b = 1.0 - _smooth((zb - 0.1 - z) / 0.3)                 # fading out under the lower lip
        lat = 1.0 - _smooth((abs(x) - (w0 * 1.06 - 0.04)) / 0.2)
        return a * b * lat * fr

    def field(p):
        j = jaw(p)
        return _mix(base(p), {"Jaw": 1.0}, j) if j > 0.0 else base(p)
    R.field = field
    R.put(R.idx("tongue crease"), ("bone", "Jaw"))
    for i in R.idx("tooth tooth_ink"):        # the upper teeth stay with the head
        R.put([i], ("stuck", R.cen([i]), "base"))
    R.put(R.idx("button buttonedge buttonhole"), ("bone", "Leg4"))
    _hat(R, "yarnbase curl curl_core", "Cuff")
    R.put(R.idx("yarn yarn_core"), ("tether", "Hat", h, h - 0.45))


