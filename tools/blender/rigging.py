def apply_pose(ao, pose, d=1.0):
    """Poses the armature object `ao` (rotations only) with a POSES entry."""
    for pb in ao.pose.bones:
        pb.rotation_mode = "QUATERNION"
        pb.rotation_quaternion = (1, 0, 0, 0)
        pb.location = (0, 0, 0)
    for name, rots in pose.items():
        pb = ao.pose.bones.get(name)
        if pb is None:
            continue
        rest = pb.bone.matrix_local.to_3x3()
        q = Matrix.Identity(3)
        for axis, deg in rots:
            if axis == "slide":                                    # move along the bone (local Y)
                pb.location = (0.0, deg, 0.0)
                continue
            if axis == "own":
                ax = Vector((0.0, 1.0, 0.0))                       # the bone's own axis, local Y
            elif axis[0] == "local":
                ax = Vector(axis[1:])                              # an axis in the bone's frame
            else:
                if axis[0] == "side":
                    axis = tuple(v * d for v in axis[1:])
                ax = rest.inverted() @ Vector(axis)
            q = Matrix.Rotation(math.radians(deg), 3, ax.normalized()) @ q
        pb.rotation_quaternion = q.to_quaternion()
