def _djdryer(R):
    _hat(R, "cushion cup cupcap headband", "Leg4")
    R.put(R.idx("lens bridge arm glint", "feat"), ("bone", "Leg4"))
    R.put(R.idx("knot tieend"), ("stuck", R.cen(R.idx("knot"))))
