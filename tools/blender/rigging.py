"""
rigging.py - a skeleton (bones + skin weights) for every Steal a Sock model, so the game can bend
them: noodle legs, tapping feet, flopping cuffs, waving tentacles, a talking puppet mouth.

`rig_sock(objs)` runs in build_all.py right after texturing.bake and before the export. It only adds
an armature object `<Name>_Rig`, vertex groups and an Armature modifier on the body and on the
`_Outline` hull: no vertex moves, so the rest pose is exactly the built (and baked) model, and the
bake's UVs and image are untouched. The GLB then carries ONE glTF skin used by both meshes.

Bone convention (src/shared/Config/SockRigConfig.luau, generated by `write_luau_config`, mirrors it):
- `Root` at the `_Base` marker, no vertex weights (Roblox rule).
- `Leg1` -> `Leg2` -> `Leg3` -> `Leg4` up the leg axis from the ankle to the cuff (a single's
  lower bones stand on its sack's leaning centre line); `Leg4` is the "head" block: it starts just
  under the googly eyes, so the face never bends. `Cuff` (child of Leg4) is the top band and the
  rolled lip.
- `Foot` (child of Leg1, from the ankle along the foot's centre line) and `Toe` (child of Foot, the
  toe cap). Singles (Socktopus, LostSock) have no foot.
- `Eye1`, `Eye2` (viewer's left first) at the eyeball centres pointing out of the eye; only the
  PUPIL rides on them, so turning one about its own axis rolls the pupil round the googly eye.
- Extras per type, each a child of what it sits on: `Hat`, `Jaw`, `Pogo`, `Monocle`, `Beard`,
  `Armor`, `Cape`, `Bills`, `Question`, `Stink`, `Fly1..3`, `Toe1..5`, `Tent<i>_<j>`,
  `Neck1..4` + `Head`, `Lake`, `Hump1..2`, `Tail` (see the per-type functions below).
- Axes (Blender bone axes, kept by the glTF exporter): local +Y runs along the bone (head -> tail),
  local +Z points to the sock's FRONT (the face: Blender -Y, Roblox/glTF +Z) as far as the bone
  allows, local +X = Y x Z. Bones that point along the front (Eye, Monocle) use local +Z = up.
  So every Leg / Cuff / Root / Jaw bone has NO rest rotation: its local axes are the model's axes.
- The armature object is at the origin, unrotated, unit scale; the body and outline are parented
  to it (the glTF exporter's canonical skinned-mesh layout), the markers are not.

Weights (at most 4 bones per vertex, normalized):
- The body: a smooth field. Up the leg each vertex blends the two nearest chain bones by height
  (smoothstep across a band round each joint; the eyes and the cuff band sit outside the bands).
  Round the instep the leg turns into the foot along the same fan of rings the body is built
  with (angle about the instep centre), and along the foot Foot hands over to Toe at the toe cap.
- Pieces that lie on the surface (stripes, decals, toga, sweatband, lint pads, drawn lines) use
  the same field per vertex, so they bend with the skin under them.
- Rigid features (eyes, rims, lids, monocles, hats, headphones, the pogo stick, beards, armour,
  fangs, buttons ...) are weighted 100% to one bone, so they never stretch or shear.
- Small stuck-on bits (sweat drops, crumbs, bolts, fins, a brooch) get the field's weights at ONE
  anchor point for every vertex: they ride the surface where they are glued, without stretching.
- Chains (tentacles, the neck) blend along their own centre line; a tether (a monocle chain, the
  dryer-sheet cape, long yarn strands) blends from its bone at one end to the skin at the other.
- The outline hull copies its weights vertex for vertex from the body piece it was inflated from
  (sockkit.finish records which vertex came from which piece), so hull and body always bend alike.
"""
import math

import bpy
import numpy as np
from mathutils import Matrix, Vector

import sockkit as K

FRONT = Vector((0.0, -1.0, 0.0))     # the face side (Roblox +Z)
UP = Vector((0.0, 0.0, 1.0))
MAX_INF = 4                          # Roblox: at most 4 bones per vertex
MIN_W = 0.004                        # weights below this are dropped (then renormalised)
CHAIN = ("Leg1", "Leg2", "Leg3", "Leg4", "Cuff")


def _smooth(t):
    t = min(max(t, 0.0), 1.0)
    return t * t * (3.0 - 2.0 * t)


def _add(out, b, w):
    if w > 0.0:
        out[b] = out.get(b, 0.0) + w


def _mix(a, b, t):
    """Weights a * (1 - t) + b * t."""
    out = {}
    for k, v in a.items():
        _add(out, k, v * (1.0 - t))
    for k, v in b.items():
        _add(out, k, v * t)
    return out


def _finalise(w):
    """At most MAX_INF influences, tiny ones dropped, normalised; never the Root."""
    items = sorted(((v, k) for k, v in w.items() if k != "Root" and v > 0.0), reverse=True)[:MAX_INF]
    items = [(v, k) for v, k in items if v >= MIN_W] or items[:1]
    tot = sum(v for v, _k in items)
    return {k: v / tot for v, k in items}


# ------------------------------------------------------------------ bones
class Bone:
    def __init__(self, name, parent, head, tail, role, index=None, seg=None, hint=None):
        self.name, self.parent, self.role, self.index, self.seg = name, parent, role, index, seg
        self.hint = hint or {}        # e.g. a Jaw's {turn = max degrees about +X, slide = max studs}
        self.head, self.tail = Vector(head), Vector(tail)
        if (self.tail - self.head).length < 0.05:            # Blender drops zero-length bones
            self.tail = self.head + UP * 0.2

    @property
    def length(self):
        return (self.tail - self.head).length


# ------------------------------------------------------------------ chains (tentacles, the neck)
class Chain:
    """Weights along a centre line `path`: bone k owns arc length knots[k]..knots[k+1], blending
    over +-blend * segment round each inner knot. Below root_blend (lo, hi) the vertex hands over
    from `base(p)` (the body it grows out of) to the first bone; past end_blend (lo, hi, bone) it
    hands over to `bone` (the neck into the Head)."""

    def __init__(self, path, bones, knots, base, root_blend=None, end_blend=None, blend=0.35):
        self.P = np.array([tuple(p) for p in path], np.float64)
        seg = np.linalg.norm(self.P[1:] - self.P[:-1], axis=1)
        self.cum = np.concatenate([[0.0], np.cumsum(seg)])
        self.bones, self.knots, self.base = bones, knots, base
        self.root_blend, self.end_blend, self.blend = root_blend, end_blend, blend

    def length(self):
        return float(self.cum[-1])

    def at(self, s):
        """Point on the path at arc length s."""
        s = min(max(s, 0.0), self.cum[-1])
        k = int(min(np.searchsorted(self.cum, s, side="right") - 1, len(self.P) - 2))
        t = (s - self.cum[k]) / max(self.cum[k + 1] - self.cum[k], 1e-9)
        return Vector(self.P[k] * (1 - t) + self.P[k + 1] * t)

    def arc_of(self, pts):
        """Arc length of the nearest path point for each point (n, 3) -> (n,)."""
        X = np.asarray(pts, np.float64)[:, None, :]
        A, B = self.P[None, :-1, :], self.P[None, 1:, :]
        AB = B - A
        t = np.clip(((X - A) * AB).sum(-1) / np.maximum((AB * AB).sum(-1), 1e-12), 0.0, 1.0)
        D = ((A + AB * t[..., None] - X) ** 2).sum(-1)
        k = D.argmin(axis=1)
        rows = np.arange(len(k))
        return self.cum[k] + t[rows, k] * (self.cum[k + 1] - self.cum[k])

    def weights(self, p, s):
        kn, bones = self.knots, self.bones
        w = {bones[0]: 1.0}
        for j in range(1, len(bones)):
            half = self.blend * min(kn[j] - kn[j - 1], kn[j + 1] - kn[j])
            if s >= kn[j] - half:
                t = _smooth((s - (kn[j] - half)) / (2 * half))
                w = {bones[j - 1]: 1.0 - t, bones[j]: t}
        if self.root_blend and s < self.root_blend[1]:
            lo, hi = self.root_blend
            w = _mix(self.base(p), w, _smooth((s - lo) / (hi - lo)))
        if self.end_blend and s > self.end_blend[0]:
            lo, hi, b = self.end_blend
            w = _mix(w, {b: 1.0}, _smooth((s - lo) / (hi - lo)))
        return w


# ------------------------------------------------------------------ the plan for one sock
class Rig:
    """Bones + how every piece is weighted, for one built sock (SockCtx `c`, body object)."""

    def __init__(self, c, body, info):
        self.c, self.body, self.info = c, body, info
        n = len(body.data.vertices)
        co = np.empty(n * 3, np.float32)
        body.data.vertices.foreach_get("co", co)
        mw = np.array(body.matrix_world, np.float64)
        co = co.reshape(-1, 3).astype(np.float64) @ mw[:3, :3].T + mw[:3, 3]
        self.co = co
        self.bones = {}
        self.assign = {}              # piece index -> target
        self.field = self.base        # the skin field (types may wrap it)
        self.eye_parent = "Leg4"
        self.cuff_bone = "Cuff"       # Sockington: the helm holds the cuff still
        self._setup_field()

    # -- pieces
    def idx(self, names, group=None, where=None):
        names = names.split() if isinstance(names, str) else names
        lo, hi = self.c.face_range
        out = []
        for i, nm in enumerate(self.info["names"]):
            if nm not in names or self.info["body"][i] is None:
                continue
            g = "body" if i < lo else ("face" if i < hi else "feat")
            if group and g != group:
                continue
            if where and not where(self.cen([i])):
                continue
            out.append(i)
        return out

    def verts(self, idxs):
        rs = [self.info["body"][i] for i in idxs]
        return np.concatenate([self.co[s:s + n] for s, n in rs]) if rs else np.zeros((0, 3))

    def cen(self, idxs):
        v = self.verts(idxs)
        return Vector(v.mean(axis=0)) if len(v) else Vector()

    def lo(self, idxs):
        return Vector(self.verts(idxs).min(axis=0))

    def hi(self, idxs):
        return Vector(self.verts(idxs).max(axis=0))

    def put(self, idxs, target):
        for i in idxs:
            self.assign[i] = target

    # -- bones
    def add(self, name, parent, head, tail, role, index=None, seg=None, hint=None):
        self.bones[name] = Bone(name, parent, head, tail, role, index, seg, hint)
        return self.bones[name]

    def dominant(self, p):
        w = self.base(p)
        return max(w, key=w.get)

    # -- the skin field
    def _setup_field(self):
        c, sh = self.c, self.c.shape
        h, cz = c.h, c.cuff_z
        self.footed = c.side != "S"
        self.d = c.d if c.d else 1.0
        z0 = sh.Pa.y if self.footed else sh.z_bot
        on_leg = [e for e in c.eyes if e[2] < h]          # SockNess carries its eyes on the head
        self.eye_lo = min(e[2] for e in on_leg) - c.eye_rim_r if on_leg else None
        self.eye_hi = max(e[2] for e in on_leg) + c.eye_rim_r if on_leg else None
        z3 = self.eye_lo - 0.2 if on_leg else z0 + 0.72 * (cz - z0)
        if self.footed:    # Leg1 = the ankle (up to the instep), Leg2 / Leg3 share the shin
            z1 = min(max(c.instep_z - 0.1, z0 + 0.3 * (z3 - z0)), z0 + 0.5 * (z3 - z0))
            z2 = (z1 + z3) / 2
        else:              # singles: the wide sack bends evenly (narrow bands would crease it)
            z1, z2 = z0 + (z3 - z0) / 3, z0 + 2 * (z3 - z0) / 3
        self.zs = [z0, z1, z2, z3, cz, h]
        # blend bands: as wide as the segments allow (they touch), except that the eyes and the
        # cuff band stay outside them (the face never bends, the cuff flops as one ring)
        up3 = 0.5 * (cz - z3)
        if on_leg:
            up3 = min(up3, self.eye_lo - z3 - 0.02)
        lo4 = min(max(cz - self.eye_hi - 0.03, 0.04), 0.15) if on_leg else 0.15
        b1, b2 = 0.5 * min(z1 - z0, z2 - z1), 0.5 * min(z2 - z1, z3 - z2)
        self.zones = [(z1 - b1, z1 + b1), (z2 - b2, z2 + b2), (z3 - 0.5 * (z3 - z2), z3 + up3),
                      (cz - lo4, cz + min(0.1, 0.45 * (h - cz)))]
        if self.footed:
            self.Q, self.Pa, self.ax = sh.Q.copy(), sh.Pa.copy(), sh.ax.copy()
            self.th_end = math.pi / 2 - sh.alpha
            self.t1, self.t_tip = sh.t1, sh.t_tip
            self.bt = min(0.15, 0.4 * (sh.t_tip - sh.t1))

    def leg(self, z):
        bones = CHAIN[:4] + (self.cuff_bone,)
        for j, (a, b) in enumerate(self.zones):
            if z < a:
                return {bones[j]: 1.0}
            if z <= b:
                t = _smooth((z - a) / (b - a))
                return {bones[j]: 1.0 - t, bones[j + 1]: t} if bones[j] != bones[j + 1] else {bones[j]: 1.0}
        return {bones[4]: 1.0}

    def foot(self, p):
        """(foot share, toe share of the foot) at p: the angle about the instep centre (the fan the
        body's rings are built on) hands the leg over to the foot."""
        if not self.footed:
            return 0.0, 0.0
        x, z = self.d * p[0], p[2]
        th = math.atan2(-(z - self.Q.y), -(x - self.Q.x))
        if th <= 0.0:
            return 0.0, 0.0
        wf = _smooth((th / self.th_end - 0.1) / 0.75)
        ta = (x - self.Pa.x) * self.ax.x + (z - self.Pa.y) * self.ax.y
        wt = _smooth((ta - (self.t1 - self.bt)) / (2 * self.bt))
        return wf, wt

    def base(self, p):
        wf, wt = self.foot(p)
        out = {}
        if wf < 1.0:
            for b, w in self.leg(p[2]).items():
                _add(out, b, w * (1.0 - wf))
        _add(out, "Foot", wf * (1.0 - wt))
        _add(out, "Toe", wf * wt)
        return out

    # -- standard bones
    def standard_bones(self):
        c, sh = self.c, self.c.shape
        z0, z1, z2, z3, z4, h = self.zs
        base_z = getattr(c, "base_z", 0.0)
        ank = Vector((0.0, 0.0, z0))
        self.add("Root", None, (0, 0, base_z), ank if z0 > base_z + 0.1 else (0, 0, base_z + 0.3), "root")
        for k, (a, b) in enumerate(((z0, z1), (z1, z2), (z2, z3), (z3, z4))):
            x, y = self.axis_at(a)
            self.add(f"Leg{k + 1}", "Root" if k == 0 else f"Leg{k}", (x, y, a), (x, y, b), "leg", index=k + 1)
        self.add("Cuff", "Leg4", (0, 0, z4), (0, 0, h), "cuff")
        if self.footed:
            d = self.d
            tp = sh.Pa + sh.ax * sh.t1
            self.add("Foot", "Leg1", ank, (d * tp.x, 0.0, tp.y), "foot")
            self.add("Toe", "Foot", (d * tp.x, 0.0, tp.y), c.toe_tip, "toe")

    def axis_at(self, z):
        """(x, y) of the leg's centre line at height z: the leg axis, except down a single's sack,
        whose centre slides toward the front-left (socks._Shape._bulb_rings). The leg bones stay
        upright (no rest rotation); they just pivot about the real middle of the sack."""
        sh = self.c.shape
        if self.footed:
            return 0.0, 0.0
        k = _smooth((sh.z_swell - z) / max(sh.z_swell - sh.z_bulb, 0.1))
        return sh.lean.x * k, sh.lean.y * k

    def eye_bones(self):
        c = self.c
        for i, (e, n) in enumerate(zip(c.eyes, c.eye_n)):
            self.add(f"Eye{i + 1}", self.eye_parent, e, Vector(e) + Vector(n).normalized() * 0.25, "eye", index=i + 1)

    def nearest_bone(self, p, prefix):
        cands = [b for b in self.bones.values() if b.name.startswith(prefix)]
        return min(cands, key=lambda b: (b.head - p).length).name

    def default_assign(self):
        """Pieces no type function claimed: the shared face and everything lying on the skin."""
        lo, hi = self.c.face_range
        for i, nm in enumerate(self.info["names"]):
            if i in self.assign:
                continue
            face = lo <= i < hi
            if i == 0:
                t = ("skin",)
            elif nm == "pupil" and any(b.role == "eye" for b in self.bones.values()):
                t = ("eye",)
            elif nm in ("eye", "eyerim", "lid", "lidline", "eyelid") or (nm == "glint" and face):
                t = ("bone", self.eye_parent)
            elif nm == "glint":
                t = ("stuck", None)
            else:
                t = ("skin",)
            self.assign[i] = t

    # -- weights
    def piece_weights(self, i, pts):
        t = self.assign[i]
        kind = t[0]
        if kind == "bone":
            return [{t[1]: 1.0}] * len(pts)
        if kind == "eye":
            cen = Vector(pts.mean(axis=0))
            return [{self.nearest_bone(cen, "Eye"): 1.0}] * len(pts)
        if kind == "near":                                 # rigid to the nearest bone named prefix*
            cen = Vector(pts.mean(axis=0))
            return [{self.nearest_bone(cen, t[1]): 1.0}] * len(pts)
        if kind == "stuck":                                # ("stuck", anchor or None[, "base"])
            anchor = t[1] if t[1] is not None else Vector(pts.mean(axis=0))
            fn = self.base if len(t) > 2 and t[2] == "base" else self.field
            return [fn(anchor)] * len(pts)
        if kind == "tether":                               # bone at height z_bone, skin at z_skin
            _k, b, z_bone, z_skin = t
            out = []
            for p in pts:
                f = _smooth((p[2] - z_skin) / (z_bone - z_skin))
                out.append(_mix(self.field(p), {b: 1.0}, f))
            return out
        if kind == "chain":
            ch = t[1]
            s = ch.arc_of(pts)
            return [ch.weights(p, si) for p, si in zip(pts, s)]
        return [self.field(p) for p in pts]               # skin

    def all_weights(self):
        """-> (body weights [dict per vertex], outline weights) from the assignments."""
        n = len(self.co)
        W = [None] * n
        for i, r in enumerate(self.info["body"]):
            if r is None:
                continue
            s, cnt = r
            for k, w in enumerate(self.piece_weights(i, self.co[s:s + cnt])):
                W[s + k] = _finalise(w)
        missing = [k for k, w in enumerate(W) if w is None]
        assert not missing, f"{len(missing)} body vertices without weights"
        return W


# ------------------------------------------------------------------ per-type extras
def _hat(R, names, parent):
    """A Hat bone on the rim's centre (where a hat rests), pointing up; the pieces ride on it."""
    ids = R.idx(names)
    h = R.c.h
    R.add("Hat", parent, (0, 0, h), (0, 0, max(R.hi(ids).z, h + 0.3)), "hat")
    R.put(ids, ("bone", "Hat"))
    return ids


def _monocle(R, ring, parts, chain, loop):
    c = R.c
    ids = R.idx(ring, "feat")
    ctr = R.cen(ids)
    e = min(range(len(c.eyes)), key=lambda i: (Vector(c.eyes[i]) - ctr).length)
    n = Vector(c.eye_n[e]).normalized()
    R.add("Monocle", R.eye_parent, ctr, ctr + n * 0.3, "accessory")
    R.put(ids + R.idx(parts, "feat"), ("bone", "Monocle"))
    z_knob = R.cen(R.idx("knob")).z
    z_loop = R.cen(R.idx(loop)).z
    R.put(R.idx(chain), ("tether", "Monocle", z_knob, z_loop))
    R.put(R.idx(loop), ("stuck", None))


def _anklebiter(R):
    ids = R.idx("fang fang_ink")
    zt = R.hi(ids).z
    # like the Puppet's: an upright bone hinged 2 units behind the grin line, so turning it about +X
    # (or sliding it down its -Y) drops the fangs a little - a chomp
    R.add("Jaw", R.dominant(Vector((0.0, 0.0, zt))), (0.0, 2.0, zt), (0.0, 2.0, zt + 0.3), "jaw",
          hint=dict(turn=4, slide=0.12))
    R.put(ids, ("bone", "Jaw"))


def _argylo(R):
    _monocle(R, "monocle", "monocle_ink lens glint knob", "chain", "loop")


def _zillionaire(R):
    _hat(R, "hatinside tophat hatband", "Cuff")
    top = R.hi(R.idx("tophat")).z

    def tucked(p):           # the bill tucked in the hat band (the others are the fountain)
        return math.hypot(p.x, p.y) < 1.2 and p.z < top - 0.6

    bills = R.idx("bill billoval billdot")
    R.put([i for i in bills if tucked(R.cen([i]))], ("bone", "Hat"))
    R.add("Bills", "Hat", (0, 0, top), (0, 0, top + 0.6), "accessory")
    R.put([i for i in bills if not tucked(R.cen([i]))], ("bone", "Bills"))
    _monocle(R, "monocle", "glint knob", "chain", "chainloop")


