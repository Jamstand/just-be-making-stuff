# ------------------------------------------------------------------ armature + weights
def _roll_ref(b):
    axis = (b.tail - b.head).normalized()
    ref = FRONT - axis * FRONT.dot(axis)
    if ref.length < 0.35:
        ref = UP - axis * UP.dot(axis)
    return ref.normalized()


def build_armature(name, bones):
    arm = bpy.data.armatures.new(name)
    ao = bpy.data.objects.new(name, arm)
    K.link(ao)
    vl = bpy.context.view_layer
    for o in vl.objects:
        o.select_set(False)
    vl.objects.active = ao
    bpy.ops.object.mode_set(mode="EDIT")
    for b in bones.values():
        eb = arm.edit_bones.new(b.name)
        eb.head, eb.tail = b.head, b.tail
        eb.use_deform = b.role != "root"
    for b in bones.values():
        eb = arm.edit_bones[b.name]
        if b.parent:
            eb.parent = arm.edit_bones[b.parent]
            eb.use_connect = False
        eb.align_roll(_roll_ref(b))
    bpy.ops.object.mode_set(mode="OBJECT")
    arm.display_type = "STICK"
    return ao


def _skin(obj, ao, W):
    for k, w in enumerate(W):
        for b, v in w.items():
            vg = obj.vertex_groups.get(b) or obj.vertex_groups.new(name=b)
            vg.add([k], v, "REPLACE")
    mod = obj.modifiers.new("Armature", "ARMATURE")
    mod.object = ao
    mod.use_vertex_groups = True
    # parented to the armature (the glTF exporter's canonical skinned-mesh layout; the armature sits
    # at the origin unrotated, so nothing moves)
    mw = obj.matrix_world.copy()
    obj.parent = ao
    obj.matrix_parent_inverse = ao.matrix_world.inverted()
    obj.matrix_world = mw


def rig_sock(objs):
    """Adds `<Name>_Rig` and skins the body and the outline (objs from socks.build_sock, after the
    bake). Returns (armature object, Rig)."""
    body = objs[0]
    outline = next(o for o in objs if o.name == body.name + "_Outline")
    R = plan(body)
    W = R.all_weights()
    # the outline: the very same weights as the body vertex it was inflated from
    WO = [None] * len(outline.data.vertices)
    for pi, s, n in R.info["outline"]:
        br = R.info["body"][pi]
        if br is not None:
            for k in range(n):
                WO[s + k] = W[br[0] + k]
        else:      # outline-only pieces: weighted like a piece of their own
            co = np.array([tuple(outline.matrix_world @ outline.data.vertices[s + k].co) for k in range(n)])
            for k, w in enumerate(R.piece_weights(pi, co)):
                WO[s + k] = _finalise(w)
    assert all(w is not None for w in WO), "outline vertices without weights"
    ao = build_armature(body.name + "_Rig", R.bones)
    _skin(body, ao, W)
    _skin(outline, ao, WO)
    for o in objs[2:]:              # glow parts riding on the sock (none yet): rigid, by position
        if o.type == "MESH" and not o.name.endswith(("_Base", "_Unit", "_Pin")):
            cen = sum((o.matrix_world @ v.co for v in o.data.vertices), Vector()) / max(len(o.data.vertices), 1)
            _skin(o, ao, [{R.dominant(cen): 1.0}] * len(o.data.vertices))
    R.W, R.WO = W, WO
    return ao, R


# ------------------------------------------------------------------ the generated Luau config
def bone_table(R):
    """[(name, fields)] in hierarchy order (parents first); fields in the order the Luau file
    writes them (role, index, seg, parent, length, then any hints)."""
    out, done = [], set()
    pending = list(R.bones.values())
    while pending:
        for b in list(pending):
            if b.parent is None or b.parent in done:
                f = [("role", b.role), ("index", b.index), ("seg", b.seg), ("parent", b.parent),
                     ("length", round(b.length, 2))] + sorted(b.hint.items())
                out.append((b.name, [(k, v) for k, v in f if v is not None]))
                done.add(b.name)
                pending.remove(b)
    return out


LUAU_HEADER = """--!strict
-- SockRigConfig: the skeleton inside every sock mesh (assets/meshes/steal-a-sock/socks/*.glb).
-- GENERATED by tools/blender/build_all.py (rigging.py) - do not edit by hand. Re-run
-- `python tools/blender/build_all.py --rig-config` after changing tools/blender/rigging.py.
--
-- Each GLB carries ONE skeleton, used by both the body and its _Outline hull (one glTF skin);
-- Roblox imports the joints as Bone instances with these names. Lengths are in studs at
-- SockScale 1 (the game scales socks x2, bones included). Left and right halves are mirror
-- images (x -> -x) with the same bones and lengths, so each type has one entry.
--
-- Bone axes: local +Y runs along the bone (head -> tail); local +Z points to the sock's front
-- (the face, model +Z) as far as the bone allows; X = Y x Z. Eye and Monocle bones point out of
-- the face, so their +Z is up instead. Root, Leg, Cuff and Jaw bones have no rest rotation: their
-- axes are the model's axes, so turning one about +X curls the part above it toward the face.
--
-- Roles:
--   root       the model origin (_Base marker); never weighted
--   leg        index 1-4 from the ankle up; Leg4 is the face block (it starts just under the
--              eyes, so the face never bends). Tested clean: 15 deg per joint bends (60 deg curls,
--              S-curves); twists about a bone's own Y up to ~10 deg per joint (Argylo's diamond
--              decals flicker past ~20). Singles (Socktopus, LostSock) bend through a wide sack:
--              keep their joints under ~10 deg each
--   cuff       the top band and rolled lip (child of Leg4); Sockington's helm holds it still
--   foot, toe  the foot from the ankle, the toe cap (footed socks only)
--   eye        index 1-2 (viewer's left first): only the pupil rides it - spin it about its own
--              Y to roll the pupil round the googly eye
--   hat        whatever sits on the head (top hat, crown, helm, headphones, wreath, hair, mop);
--              tight ones (Sockington's helm, Sockrates' wreath) want small tilts (< ~8 deg)
--   jaw        turn about +X by up to `turn` degrees, or slide down (local -Y) by up to `slide`
--              studs, to open (PuppetSupreme) or chomp (AnkleBiter's fangs)
--   pogo       Sockhopper's stick (child of Root, pivot at its rubber tip)
--   tentacle   index = tentacle 1-6, seg = 1-3 from the sack to the tip
--   neck, head SockNess: Neck1-4 out of the opening, then the Head (eyes ride on it)
--   digit      ToeToe's five toes (1 = big toe), children of Toe
--   fly        Stinkolino's flies (children of Root: they buzz on their own)
--   ground     stays on the floor (SockNess' suds puddle); hump (index), tail ride on it
--   accessory  monocle, beard, armour, dryer-sheet cape, bills, question mark, stink cloud, rose,
--              fork
--   dangle     a floppy hanging part that swings with the sock's motion: index = which part,
--              seg = 1.. from where it hangs to its tip (nightcap, headband tails, cape halves,
--              bell, earring, hat tips, lappets, a dragon's tail, loose bandage ends); `swing` =
--              the most it bends cleanly per bone (degrees)
--   spring     a short stiff part that wobbles on a spring (hair curl, antenna, moustache);
--              `wobble` = the most it tilts cleanly (degrees)
--   wing       index 1-2 (viewer's left first): flaps about its own Y; `flap` = the most it
--              opens or closes cleanly (degrees)
--   jet        a jetpack nozzle (index 1-2): local +Y points out of the nozzle, for a flame
"""


def _luau_value(v):
    if isinstance(v, str):
        return '"' + v + '"'
    return f"{v:g}" if isinstance(v, float) else str(v)


def write_luau_config(path, tables, order):
    """tables: {key: bone_table}; key = type id (or "<id>_L" / "<id>_R" if the halves differ)."""
    hints = sorted({k for key in order for _n, f in tables[key] for k, _v in f
                    if k not in ("role", "index", "seg", "parent", "length")})
    lines = LUAU_HEADER.rstrip("\n").split("\n") + [
        "",
        "export type BoneInfo = {",
        "\trole: string,",
        "\tindex: number?,",
        "\tseg: number?,",
        "\tparent: string?,",
        "\tlength: number,",
    ] + [f"\t{k}: number?," for k in hints] + [
        "}",
        "",
        "local SockRigConfig = {}",
        "",
        "-- the leg chain from the ankle up; Cuff hangs off Leg4",
        'SockRigConfig.Chain = { "Leg1", "Leg2", "Leg3", "Leg4" }',
        "",
        "SockRigConfig.Types = {",
    ]
    for key in order:
        lines.append(f"\t{key} = {{")
        for name, fields in tables[key]:
            lines.append(f"\t\t{name} = {{ " + ", ".join(f"{k} = {_luau_value(v)}" for k, v in fields) + " },")
        lines.append("\t},")
    lines += ["} :: { [string]: { [string]: BoneInfo } }", "", "return SockRigConfig", ""]
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines))


